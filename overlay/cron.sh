#!/usr/bin/env bash
# ============================================================
#  نقطة دخول الـ cron — BP Engine
#
#  لوحة تحكم الاستضافة المشتركة بتاخد سطر واحد وبس، ومراجعته بعدين
#  محتاجة دخول للوحة. فالسطر هناك بينده الملف ده وخلاص:
#
#      * * * * * bash ~/bp-engine/cron.sh
#
#  وأي تعديل في المنطق بيحصل هنا وبيتنشر مع الرفع العادي.
# ============================================================
set -uo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")" || exit 1

# مسار الـ PHP بيختلف من استضافة للتانية، وبيئة الـ cron أفقر من بيئة
# الـ SSH فـ PATH ممكن يبقى ناقص — بنجرّب المتغير الصريح الأول.
PHP="${PHP_BIN:-$(command -v php || true)}"
[ -n "$PHP" ] || PHP=/usr/bin/php

# stdout بيتقفل: `schedule:run` بيطبع سطر في كل دقيقة حتى لو مفيش حاجة
# اشتغلت — 1,440 سطر في اليوم بيدفنوا الأخطاء الحقيقية.
# stderr بس هو اللي بيتسجّل، فالملف ده لو فيه حاجة يبقى فيه مشكلة فعلًا.
exec "$PHP" artisan schedule:run >/dev/null 2>>storage/logs/schedule.log
